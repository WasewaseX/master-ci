#!/usr/bin/env python3
"""hook_install.py - write the per-edit hook configs for coding agents.

The scanaislop product treats the per-edit hook as the primary install
(``aislop hook install``); Master CI's engines existed but nothing
wired them into an agent's edit loop. This generator writes the two
hook shapes that matter, plus a recipe sheet for agents without a hook
API:

- ``--agent claude``    Claude Code PostToolUse hook. When
                        .claude/settings.json does not exist it is
                        created; when it exists the hook block is
                        written to .claude/master-ci-hook.json and
                        printed for a manual merge - the generator
                        never silently rewrites a consumer's settings.
- ``--agent pre-commit``
                        .git/hooks/pre-commit that gates the staged
                        files on every commit. Refused when the hook
                        already exists unless --force.
- ``--agent recipe``    print the command lines for agents and shells
                        without a hook API (Codex, plain editors).

Exit codes: 0 written or printed; 2 refused (an existing file the
generator will not overwrite without --force, or an unusable root).
Every generated artifact calls scripts/hook_gate.py relative to the
repo root, so the template must be checked out (or copied) with its
scripts/ directory - the hook is a gate over the consumer's own copy,
not over a pip-installed tool.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path

GATE_COMMAND = "python3 scripts/hook_gate.py --stdin-claude"

CLAUDE_HOOK_BLOCK = {
    "hooks": {
        "PostToolUse": [
            {
                "matcher": "Edit|Write|MultiEdit",
                "hooks": [{"type": "command", "command": GATE_COMMAND}],
            }
        ]
    }
}

PRE_COMMIT_SCRIPT = """#!/bin/sh
# master-ci per-commit gate (generated by scripts/hook_install.py).
# Gates the staged files with the same engines the CI scan uses;
# advisory findings print, blocking findings fail the commit.
changed=$(git diff --cached --name-only --diff-filter=ACMR)
[ -z "$changed" ] && exit 0
exec python3 scripts/hook_gate.py $changed
"""

RECIPES = """# master-ci per-edit recipes

Claude Code (settings.json hooks -> PostToolUse):
    python3 scripts/hook_install.py --agent claude

Git (every commit, staged files only):
    python3 scripts/hook_install.py --agent pre-commit

Any agent with a run-after-edit command (Codex, editors):
    python3 scripts/hook_gate.py <file> [<file> ...]

Claude Code PostToolUse payload (one shot, manual):
    python3 scripts/hook_gate.py --stdin-claude
"""


def _install_claude(root: Path) -> int:
    claude_dir = root / ".claude"
    settings = claude_dir / "settings.json"
    snippet = claude_dir / "master-ci-hook.json"
    claude_dir.mkdir(parents=True, exist_ok=True)
    if settings.exists():
        # Never rewrite a consumer's settings: ship the block as its own
        # artifact and tell the human to merge it.
        snippet.write_text(json.dumps(CLAUDE_HOOK_BLOCK, indent=2) + "\n", encoding="utf-8")
        print(
            f"hook block written to {snippet.relative_to(root)} "
            f"- merge it into {settings.relative_to(root)} by hand "
            "(the generator does not touch an existing settings.json)"
        )
        return 0
    settings.write_text(json.dumps(CLAUDE_HOOK_BLOCK, indent=2) + "\n", encoding="utf-8")
    print(f"Claude Code hook written to {settings.relative_to(root)} (PostToolUse -> hook_gate)")
    return 0


def _install_pre_commit(root: Path, force: bool) -> int:
    hooks_dir = root / ".git" / "hooks"
    if not hooks_dir.is_dir():
        print(
            "hook-install: no .git/hooks directory - run inside a git "
            "checkout (fail-closed, nothing written)",
            file=sys.stderr,
        )
        return 2
    target = hooks_dir / "pre-commit"
    if target.exists() and not force:
        print(
            f"hook-install: {target} already exists; pass --force to "
            "replace it (refused by default)",
            file=sys.stderr,
        )
        return 2
    target.write_text(PRE_COMMIT_SCRIPT, encoding="utf-8")
    target.chmod(0o755)
    print(f"pre-commit gate written to {target.relative_to(root)}")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Install master-ci agent hooks")
    parser.add_argument(
        "--agent",
        required=True,
        choices=("claude", "pre-commit", "recipe"),
        help="Which hook shape to install",
    )
    parser.add_argument("--root", type=Path, default=Path.cwd(), help="Repo root")
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite an existing pre-commit hook (default: refuse)",
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()
    if not (root / "scripts" / "hook_gate.py").is_file():
        print(
            "hook-install: scripts/hook_gate.py not found under the root - "
            "the hook gates the consumer's own copy of the template",
            file=sys.stderr,
        )
        return 2
    if args.agent == "recipe":
        print(RECIPES, end="")
        return 0
    if args.agent == "claude":
        return _install_claude(root)
    return _install_pre_commit(root, args.force)


if __name__ == "__main__":
    raise SystemExit(main())
